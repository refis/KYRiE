def show_panel(dialog):
    if not dialog.property('workspaceGeometryReady'):
        area=dialog.screen().availableGeometry()
        dialog.resize(min(dialog.width(),max(320,area.width()-40)),min(dialog.height(),max(240,area.height()-60)))
        parent=dialog.parentWidget()
        center=parent.frameGeometry().center() if parent else area.center()
        left=max(area.left(),min(center.x()-dialog.width()//2,area.right()-dialog.width()+1))
        top=max(area.top(),min(center.y()-dialog.height()//2,area.bottom()-dialog.height()+1))
        dialog.move(left,top)
        dialog.setProperty('workspaceGeometryReady',True)
    dialog.show()
    dialog.raise_()
    dialog.activateWindow()


